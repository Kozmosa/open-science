import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(frontendRoot, '..');
const generatedRoot = resolve(frontendRoot, 'src/generated/transport');
const checkOnly = process.argv.includes('--check');
const outputRoot = checkOnly ? mkdtempSync(join(tmpdir(), 'openscience-transport-')) : generatedRoot;
const schemaPath = join(outputRoot, 'openapi.json');
const header = '// AUTO-GENERATED by npm run generate:transport. DO NOT EDIT.\n';

function run(command, args, cwd) {
  execFileSync(command, args, {
    cwd,
    env: { ...process.env, UV_CACHE_DIR: process.env.UV_CACHE_DIR || '/tmp/uv-cache' },
    stdio: 'inherit',
  });
}

function filesUnder(root) {
  return readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name))
    .sort();
}

function compareGenerated(actualRoot, expectedRoot) {
  const actual = filesUnder(actualRoot).map((path) => relative(actualRoot, path));
  const expected = filesUnder(expectedRoot).map((path) => relative(expectedRoot, path));
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(`generated transport file list drifted\nexpected: ${expected.join(', ')}\nactual: ${actual.join(', ')}`);
  }
  for (const name of actual) {
    if (!readFileSync(join(actualRoot, name)).equals(readFileSync(join(expectedRoot, name)))) {
      throw new Error(`generated transport contract drifted: ${name}`);
    }
  }
}

try {
  run('uv', ['run', 'python', 'scripts/export_transport_openapi.py', '--output', schemaPath], repoRoot);
  const generatorOutput = join(outputRoot, '.generator');
  mkdirSync(generatorOutput, { recursive: true });
  run(
    resolve(frontendRoot, 'node_modules/.bin/openapi-ts'),
    [
      '--input',
      schemaPath,
      '--output',
      generatorOutput,
      '--plugins',
      '@hey-api/typescript',
      '--no-log-file',
    ],
    frontendRoot,
  );
  writeFileSync(join(outputRoot, 'schema.ts'), readFileSync(join(generatorOutput, 'types.gen.ts')));
  rmSync(generatorOutput, { recursive: true, force: true });

  const schemaBytes = readFileSync(schemaPath);
  const schema = JSON.parse(schemaBytes.toString('utf8'));
  const generatedOperations = {};
  for (const path of Object.keys(schema.paths).sort()) {
    for (const method of ['delete', 'get', 'head', 'options', 'patch', 'post', 'put']) {
      const operation = schema.paths[path][method];
      if (!operation) continue;
      const canonical = path.startsWith('/api/');
      generatedOperations[operation.operationId] = {
        method: method.toUpperCase(),
        path,
        clientPath: canonical ? path.slice('/api'.length) : path,
        canonical,
        deprecated: operation.deprecated === true,
      };
    }
  }
  writeFileSync(
    join(outputRoot, 'operations.ts'),
    `${header}export const transportOperations = ${JSON.stringify(generatedOperations, null, 2)} as const;\n`,
  );
  writeFileSync(
    join(outputRoot, 'index.ts'),
    `${header}export type * from './schema';\nexport { transportOperations } from './operations';\n`,
  );
  const generatorPackage = JSON.parse(
    readFileSync(resolve(frontendRoot, 'node_modules/@hey-api/openapi-ts/package.json'), 'utf8'),
  );
  const manifest = {
    generator: '@hey-api/openapi-ts',
    generatorVersion: generatorPackage.version,
    openapiVersion: schema.openapi,
    schemaSha256: createHash('sha256').update(schemaBytes).digest('hex'),
  };
  writeFileSync(join(outputRoot, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  writeFileSync(
    join(outputRoot, 'README.md'),
    '# Generated HTTP transport contract\n\nThese files are generated from FastAPI/Pydantic OpenAPI. Do not edit them by hand. Run `npm --prefix frontend run generate:transport` from the repository root.\n',
  );

  if (checkOnly) compareGenerated(outputRoot, generatedRoot);
} finally {
  if (checkOnly) rmSync(outputRoot, { recursive: true, force: true });
}
